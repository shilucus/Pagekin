import { describe, expect, it } from 'vitest'
import type { GenerationTask } from '../../services/generation/generation-harness'
import { injectWritingSkillPrompt } from '../writing-skill-task'

const skill = { name: 'Synthetic guidance', content: 'Preserve the stated facts.' }
const makeTask = (): GenerationTask => ({
  purpose: 'review-chapter', output: 'structured-data', reasoningStage: 'review',
  messages: [{ role: 'system', content: 'System contract' }, { role: 'assistant', content: 'Prior response' },
    { role: 'user', content: 'Author task' }, { role: 'user', content: 'Unchanged later message' }],
})

describe('shared stage writing-skill task injection', () => {
  it.each([undefined, null])('keeps the original task identity without a selected skill (%s)', selected => {
    const task = makeTask()
    expect(injectWritingSkillPrompt(task, 'zh-CN', selected)).toEqual({ task })
    expect(injectWritingSkillPrompt(task, 'zh-CN', selected).task).toBe(task)
  })

  it('keeps the original task identity when there is no user message', () => {
    const task: GenerationTask = { ...makeTask(), messages: [{ role: 'system', content: 'Only a system message' }] }
    expect(injectWritingSkillPrompt(task, 'en-US', skill)).toEqual({ task })
    expect(injectWritingSkillPrompt(task, 'en-US', skill).task).toBe(task)
  })

  it.each(['zh-CN', 'en-US'] as const)('preserves the legacy full message and budget contract in %s', language => {
    const task = makeTask(), original = structuredClone(task)
    // Exact text from base-command.ts at immutable parent c8fc65fa, not generated by the new helper.
    const block = language === 'en-US'
      ? '[Supplemental writing skill: Synthetic guidance]\nThis guidance may improve craft, but author facts, the project writing language, and the output contract below always take priority.\nPreserve the stated facts.'
      : '【补充写作 Skill：Synthetic guidance】\n以下内容只能补充创作方法；作者事实、项目写作语言和后续输出合同始终优先。\nPreserve the stated facts.'
    const messages = [task.messages[0]!, task.messages[1]!, { role: 'user' as const, content: `${block}\n\nAuthor task` }, task.messages[3]!]
    const result = injectWritingSkillPrompt(task, language, skill)
    expect(result).toEqual({ skillName: skill.name, task: { ...task, messages,
      promptBudget: { limitUtf8Bytes: Buffer.byteLength(messages.map(message => message.content).join(''), 'utf8'),
        sections: [{ sectionName: 'writing-skill', displayName: skill.name, messageIndex: 2, finalText: block }] } } })
    expect(task).toEqual(original)
    expect(result.task.messages[0]).toBe(task.messages[0])
    expect(result.task.messages[1]).toBe(task.messages[1])
    expect(result.task.messages[3]).toBe(task.messages[3])
    expect(result.task.messages[2]).not.toBe(task.messages[2])
  })

  it('preserves an existing budget and protected sections after the skill section', () => {
    const prior = { sectionName: 'source', messageIndex: 2, finalText: 'Author task', limitUtf8Bytes: 100 }
    const task: GenerationTask = { ...makeTask(), promptBudget: { limitUtf8Bytes: 2048, sections: [prior] } }
    const result = injectWritingSkillPrompt(task, 'en-US', skill)
    expect(result.task.promptBudget?.limitUtf8Bytes).toBe(2048)
    expect(result.task.promptBudget?.sections).toHaveLength(2)
    expect(result.task.promptBudget?.sections[1]).toBe(prior)
    expect(task.promptBudget?.sections).toEqual([prior])
    expect(task.messages[2]!.content).toBe('Author task')
  })
})
